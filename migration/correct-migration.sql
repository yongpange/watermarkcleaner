-- WatermarkCleaner 数据库迁移修正脚本
-- 基于实际的数据库结构

-- =====================================================
-- 阶段1：备份当前的 public schema 表（因为这些是实际使用的表）
-- =====================================================

-- 创建备份schema
CREATE SCHEMA IF NOT EXISTS backup_before_migration;

-- 备份现有的 public.users 表（这是实际使用的用户表）
DROP TABLE IF EXISTS backup_before_migration.users;
CREATE TABLE backup_before_migration.users AS SELECT * FROM public.users;

-- 备份其他相关表
DROP TABLE IF EXISTS backup_before_migration.orders;
CREATE TABLE backup_before_migration.orders AS SELECT * FROM public.orders;

DROP TABLE IF EXISTS backup_before_migration.apikeys;
CREATE TABLE backup_before_migration.apikeys AS SELECT * FROM public.apikeys;

DROP TABLE IF EXISTS backup_before_migration.credits;
CREATE TABLE backup_before_migration.credits AS SELECT * FROM public.credits;

DROP TABLE IF EXISTS backup_before_migration.conversions;
CREATE TABLE backup_before_migration.conversions AS SELECT * FROM public.conversions;

-- =====================================================
-- 阶段2：创建新的 wmc_ 前缀表
-- =====================================================

-- 1. 创建 wmc_users 表（基于实际的 public.users 结构）
CREATE TABLE IF NOT EXISTS public.wmc_users (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uuid TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    nickname TEXT,
    avatar_url TEXT,
    locale TEXT,
    signin_type TEXT,
    signin_ip TEXT,
    signin_provider TEXT,
    signin_openid TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    invite_code TEXT,
    invited_by TEXT,
    is_affiliate BOOLEAN DEFAULT FALSE
);

-- 2. 创建 wmc_orders 表
CREATE TABLE IF NOT EXISTS public.wmc_orders (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_no TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    user_uuid TEXT NOT NULL,
    user_email TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    interval TEXT,
    expired_at TIMESTAMPTZ,
    status TEXT NOT NULL,
    stripe_session_id TEXT,
    credits INTEGER NOT NULL,
    currency TEXT,
    sub_id TEXT,
    sub_interval_count INTEGER,
    sub_cycle_anchor INTEGER,
    sub_period_end INTEGER,
    sub_period_start INTEGER,
    sub_times INTEGER,
    product_id TEXT,
    product_name TEXT,
    valid_months INTEGER,
    order_detail TEXT,
    paid_at TIMESTAMPTZ,
    paid_email TEXT,
    paid_detail TEXT
);

-- 3. 创建 wmc_apikeys 表
CREATE TABLE IF NOT EXISTS public.wmc_apikeys (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    api_key TEXT NOT NULL,
    title TEXT,
    user_uuid TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    status TEXT
);

-- 4. 创建 wmc_credits 表
CREATE TABLE IF NOT EXISTS public.wmc_credits (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    trans_no TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    user_uuid TEXT NOT NULL,
    trans_type TEXT NOT NULL,
    credits INTEGER NOT NULL,
    order_no TEXT,
    expired_at TIMESTAMPTZ
);

-- 5. 创建 wmc_conversions 表（图片转换历史）
CREATE TABLE IF NOT EXISTS public.wmc_conversions (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    uuid TEXT UNIQUE NOT NULL,
    user_uuid TEXT,
    file_id TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_size INTEGER NOT NULL,
    file_type TEXT NOT NULL,
    file_url TEXT,
    status TEXT NOT NULL,
    progress INTEGER DEFAULT 0,
    result JSONB,
    error JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ
);

-- =====================================================
-- 阶段3：迁移数据
-- =====================================================

-- 迁移用户数据
INSERT INTO public.wmc_users (id, uuid, email, created_at, nickname, avatar_url, locale, signin_type, signin_ip, signin_provider, signin_openid, updated_at, invite_code, invited_by, is_affiliate)
SELECT id, uuid, email, created_at, nickname, avatar_url, locale, signin_type, signin_ip, signin_provider, signin_openid, updated_at, invite_code, invited_by, is_affiliate
FROM public.users
ON CONFLICT (id) DO NOTHING;

-- 迁移订单数据
INSERT INTO public.wmc_orders (id, order_no, created_at, user_uuid, user_email, amount, interval, expired_at, status, stripe_session_id, credits, currency, sub_id, sub_interval_count, sub_cycle_anchor, sub_period_end, sub_period_start, sub_times, product_id, product_name, valid_months, order_detail, paid_at, paid_email, paid_detail)
SELECT id, order_no, created_at, user_uuid, user_email, amount, interval, expired_at, status, stripe_session_id, credits, currency, sub_id, sub_interval_count, sub_cycle_anchor, sub_period_end, sub_period_start, sub_times, product_id, product_name, valid_months, order_detail, paid_at, paid_email, paid_detail
FROM public.orders
ON CONFLICT (id) DO NOTHING;

-- 迁移API密钥数据
INSERT INTO public.wmc_apikeys (id, api_key, title, user_uuid, created_at, status)
SELECT id, api_key, title, user_uuid, created_at, status
FROM public.apikeys
ON CONFLICT (id) DO NOTHING;

-- 迁移积分数据
INSERT INTO public.wmc_credits (id, trans_no, created_at, user_uuid, trans_type, credits, order_no, expired_at)
SELECT id, trans_no, created_at, user_uuid, trans_type, credits, order_no, expired_at
FROM public.credits
ON CONFLICT (id) DO NOTHING;

-- 迁移转换历史数据
INSERT INTO public.wmc_conversions (id, uuid, user_uuid, file_id, file_name, file_size, file_type, file_url, status, progress, result, error, created_at, completed_at, expires_at)
SELECT id, uuid, user_uuid, file_id, file_name, file_size, file_type, file_url, status, progress, result, error, created_at, completed_at, expires_at
FROM public.conversions
ON CONFLICT (id) DO NOTHING;

-- =====================================================
-- 阶段4：创建索引
-- =====================================================

-- wmc_users 索引
CREATE INDEX IF NOT EXISTS idx_wmc_users_uuid ON public.wmc_users(uuid);
CREATE INDEX IF NOT EXISTS idx_wmc_users_email ON public.wmc_users(email);

-- wmc_orders 索引
CREATE INDEX IF NOT EXISTS idx_wmc_orders_user_uuid ON public.wmc_orders(user_uuid);
CREATE INDEX IF NOT EXISTS idx_wmc_orders_created ON public.wmc_orders(created_at);

-- wmc_apikeys 索引
CREATE INDEX IF NOT EXISTS idx_wmc_apikeys_user_uuid ON public.wmc_apikeys(user_uuid);

-- wmc_credits 索引
CREATE INDEX IF NOT EXISTS idx_wmc_credits_user_uuid ON public.wmc_credits(user_uuid);
CREATE INDEX IF NOT EXISTS idx_wmc_credits_created ON public.wmc_credits(created_at);

-- wmc_conversions 索引
CREATE INDEX IF NOT EXISTS idx_wmc_conversions_user_uuid ON public.wmc_conversions(user_uuid);
CREATE INDEX IF NOT EXISTS idx_wmc_conversions_created ON public.wmc_conversions(created_at);
CREATE INDEX IF NOT EXISTS idx_wmc_conversions_status ON public.wmc_conversions(status);

-- =====================================================
-- 阶段5：验证迁移结果
-- =====================================================

-- 显示迁移统计
SELECT
    'wmc_users' as table_name,
    (SELECT COUNT(*) FROM public.wmc_users) as new_count,
    (SELECT COUNT(*) FROM public.users) as old_count
UNION ALL
SELECT
    'wmc_orders' as table_name,
    (SELECT COUNT(*) FROM public.wmc_orders) as new_count,
    (SELECT COUNT(*) FROM public.orders) as old_count
UNION ALL
SELECT
    'wmc_apikeys' as table_name,
    (SELECT COUNT(*) FROM public.wmc_apikeys) as new_count,
    (SELECT COUNT(*) FROM public.apikeys) as old_count
UNION ALL
SELECT
    'wmc_credits' as table_name,
    (SELECT COUNT(*) FROM public.wmc_credits) as new_count,
    (SELECT COUNT(*) FROM public.credits) as old_count
UNION ALL
SELECT
    'wmc_conversions' as table_name,
    (SELECT COUNT(*) FROM public.wmc_conversions) as new_count,
    (SELECT COUNT(*) FROM public.conversions) as old_count
ORDER BY table_name;